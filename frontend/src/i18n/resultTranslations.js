export const translateResult = (result, language) => {
  const translations = resultTranslations[language] || resultTranslations.en;
  const translatedResult = { ...result };

  // Translate disease/breed title and description
  if (result.model_type === 'disease' && result.class_name) {
    const diseaseInfo = translations.diseases[result.class_name];
    if (diseaseInfo) {
      translatedResult.information = {
        ...result.information,
        title: diseaseInfo.title,
        description: diseaseInfo.description,
      };
    }
  } else if (result.model_type === 'breed' && result.class_name) {
    const breedInfo = translations.breeds[result.class_name];
    if (breedInfo) {
      translatedResult.information = {
        ...result.information,
        title: breedInfo.title,
        market_demand: breedInfo.market_demand,
        general_weight: breedInfo.general_weight,
        market_price: breedInfo.market_price,
      };
    }
  }

  // Translate labels
  translatedResult.labels = translations.labels;

  return translatedResult;
};
