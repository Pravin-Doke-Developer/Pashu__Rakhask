# Common image extensions
SUPPORTED_EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp", ".tiff", ".tif", ".webp"}


def load_validation_report(dataset_dir: Path) -> dict | None:
    """
    Load the validation report generated by validate_dataset.py.
    Returns None if no report exists.
    """
    report_path = dataset_dir / "validation_report.json"
    if report_path.exists():
        with open(report_path, "r", encoding="utf-8") as f:
            return json.load(f)
    return None


def get_corrupt_paths(report: dict | None) -> set[str]:
    """Extract the set of corrupt image paths from the validation report."""
    if not report:
        return set()

    corrupt = set()
    details = report.get("corrupt_files", {}).get("details", {})
    for class_name, entries in details.items():
        for entry in entries:
            corrupt.add(entry["path"])
    return corrupt


def collect_images(
    dataset_dir: Path,
    exclude_paths: set[str] | None = None,
) -> dict[str, list[Path]]:
    """
    Collect all valid image paths organized by class.

    Args:
        dataset_dir: Root directory containing class folders.
        exclude_paths: Set of absolute paths to skip (e.g., corrupt images).

    Returns:
        Dict mapping class_name -> list of image Paths.
    """
    dataset_dir = Path(dataset_dir)
    exclude_paths = {str(Path(p).resolve()) for p in (exclude_paths or set())}
    classes = {}

    def _add_if_valid(folder: Path, class_name: str):
        images = []
        for f in sorted(folder.iterdir()):
            if f.is_file() and f.suffix.lower() in SUPPORTED_EXTENSIONS:
                if str(f.resolve()) not in exclude_paths:
                    images.append(f)
        if images:
            classes[class_name] = images

    for entry in sorted(dataset_dir.iterdir()):
        if not entry.is_dir():
            continue

        if any(f.is_file() and f.suffix.lower() in SUPPORTED_EXTENSIONS for f in entry.iterdir()):
            _add_if_valid(entry, entry.name)
            continue

        for child in sorted(entry.iterdir()):
            if child.is_dir() and any(
                f.is_file() and f.suffix.lower() in SUPPORTED_EXTENSIONS for f in child.iterdir()
            ):
                _add_if_valid(child, child.name)

    return classes


def stratified_split(
    class_images: dict[str, list[Path]],
    train_ratio: float,
    val_ratio: float,
    test_ratio: float,
    seed: int,
) -> dict[str, dict[str, list[Path]]]:
    """
    Create stratified train/val/test splits.

    How it works:
    1. For each class, shuffle the images (with a fixed random seed).
    2. Split each class independently according to the ratios.
    3. This ensures every class is represented proportionally in every split.

    The fixed seed makes the split reproducible — running the script
    twice with the same seed produces the exact same splits.

    Args:
        class_images: Dict of class_name -> list of image paths.
        train_ratio: Fraction for training (e.g., 0.70).
        val_ratio: Fraction for validation (e.g., 0.15).
        test_ratio: Fraction for testing (e.g., 0.15).
        seed: Random seed for reproducibility.

    Returns:
        Dict with keys 'train', 'val', 'test', each mapping to
        a dict of class_name -> list of image paths.
    """
    random.seed(seed)

    splits = {"train": {}, "val": {}, "test": {}}

    for class_name, images in class_images.items():
        # Shuffle with the fixed seed
        shuffled = images.copy()
        random.shuffle(shuffled)

        n = len(shuffled)
        n_train = int(n * train_ratio)
        n_val = int(n * val_ratio)
        # Test gets whatever remains — avoids rounding errors losing images
        n_test = n - n_train - n_val

        splits["train"][class_name] = shuffled[:n_train]
        splits["val"][class_name] = shuffled[n_train:n_train + n_val]
        splits["test"][class_name] = shuffled[n_train + n_val:]

        # Safety check
        assert len(splits["train"][class_name]) + \
               len(splits["val"][class_name]) + \
               len(splits["test"][class_name]) == n, \
               f"Split count mismatch for {class_name}!"

    return splits


def copy_splits(
    splits: dict[str, dict[str, list[Path]]],
    output_dir: Path,
    use_symlinks: bool = False,
) -> dict:
    """
    Copy (or symlink) images into the split directory structure.

    Creates:
        output_dir/train/ClassName/image.jpg
        output_dir/val/ClassName/image.jpg
        output_dir/test/ClassName/image.jpg

    Returns a manifest dict recording every file placement.
    """
    manifest = {"splits": {}}

    for split_name, class_images in splits.items():
        manifest["splits"][split_name] = {}

        for class_name, images in class_images.items():
            dest_dir = output_dir / split_name / class_name
            dest_dir.mkdir(parents=True, exist_ok=True)

            file_list = []
            for img_path in tqdm(
                images,
                desc=f"  {split_name}/{class_name}",
                unit="img",
                leave=False,
            ):
                dest_path = dest_dir / img_path.name

                # Handle name collisions (rare but possible)
                if dest_path.exists():
                    stem = img_path.stem
                    suffix = img_path.suffix
                    counter = 1
                    while dest_path.exists():
                        dest_path = dest_dir / f"{stem}_{counter}{suffix}"
                        counter += 1

                if use_symlinks:
                    os.symlink(img_path.resolve(), dest_path)
                else:
                    shutil.copy2(img_path, dest_path)

                file_list.append({
                    "source": str(img_path),
                    "destination": str(dest_path),
                })

            manifest["splits"][split_name][class_name] = {
                "count": len(file_list),
                "files": file_list,
            }

    return manifest


def print_split_summary(splits: dict[str, dict[str, list[Path]]]):
    """Print a formatted table of split statistics."""
    classes = sorted(list(splits["train"].keys()))

    # Header
    print(f"\n{'':30s} {'Train':>8s} {'Val':>8s} {'Test':>8s} {'Total':>8s}")
    print(f"{'─'*30} {'─'*8} {'─'*8} {'─'*8} {'─'*8}")

    totals = {"train": 0, "val": 0, "test": 0}

    for cls in classes:
        n_train = len(splits["train"].get(cls, []))
        n_val = len(splits["val"].get(cls, []))
        n_test = len(splits["test"].get(cls, []))
        total = n_train + n_val + n_test

        totals["train"] += n_train
        totals["val"] += n_val
        totals["test"] += n_test

        print(f"  {cls:28s} {n_train:8d} {n_val:8d} {n_test:8d} {total:8d}")

    grand_total = totals["train"] + totals["val"] + totals["test"]
    print(f"{'─'*30} {'─'*8} {'─'*8} {'─'*8} {'─'*8}")
    print(f"  {'TOTAL':28s} {totals['train']:8d} {totals['val']:8d} {totals['test']:8d} {grand_total:8d}")

    # Percentages
    if grand_total > 0:
        print(f"  {'PERCENTAGE':28s} "
              f"{100*totals['train']/grand_total:7.1f}% "
              f"{100*totals['val']/grand_total:7.1f}% "
              f"{100*totals['test']/grand_total:7.1f}%")
    print()


def main():
    parser = argparse.ArgumentParser(
        description="Create stratified train/val/test splits from a class-folder dataset.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Example:
    python split_dataset.py --dataset_dir ../../datasets/disease \\
                            --output_dir ../../datasets/disease_split
        """,
    )
    parser.add_argument(
        "--dataset_dir", type=str, required=True,
        help="Path to the original dataset (with class folders).",
    )
    parser.add_argument(
        "--output_dir", type=str, required=True,
        help="Path for the split dataset output.",
    )
    parser.add_argument(
        "--train_ratio", type=float, default=0.70,
        help="Fraction of data for training (default: 0.70).",
    )
    parser.add_argument(
        "--val_ratio", type=float, default=0.15,
        help="Fraction of data for validation (default: 0.15).",
    )
    parser.add_argument(
        "--test_ratio", type=float, default=0.15,
        help="Fraction of data for testing (default: 0.15).",
    )
    parser.add_argument(
        "--seed", type=int, default=42,
        help="Random seed for reproducibility (default: 42).",
    )
    parser.add_argument(
        "--symlinks", action="store_true",
        help="Use symlinks instead of copying files (saves disk space).",
    )
    parser.add_argument(
        "--exclude_corrupt", action="store_true", default=True,
        help="Exclude corrupt images found by validate_dataset.py (default: True).",
    )

    args = parser.parse_args()

    # --- Validate ratios ---
    total_ratio = args.train_ratio + args.val_ratio + args.test_ratio
    if abs(total_ratio - 1.0) > 0.01:
        print(f"❌ Error: Ratios must sum to 1.0 (got {total_ratio:.2f})")
        print(f"   train={args.train_ratio}, val={args.val_ratio}, test={args.test_ratio}")
        sys.exit(1)

    dataset_dir = Path(args.dataset_dir).resolve()
    output_dir = Path(args.output_dir).resolve()

    if not dataset_dir.exists():
        print(f"❌ Error: Dataset directory not found: {dataset_dir}")
        sys.exit(1)

    if output_dir.exists():
        print(f"⚠️ Output directory already exists: {output_dir}")
        if sys.stdin is not None and hasattr(sys.stdin, "isatty") and sys.stdin.isatty():
            response = input("   Overwrite? (y/N): ").strip().lower()
            if response != "y":
                print("   Aborted.")
                sys.exit(0)
        else:
            print("   Non-interactive session detected; overwriting without prompting.")
        shutil.rmtree(output_dir)

    # --- Load validation report ---
    corrupt_paths = set()
    if args.exclude_corrupt:
        report = load_validation_report(dataset_dir)
        if report:
            corrupt_paths = get_corrupt_paths(report)
            if corrupt_paths:
                print(f"📋 Loaded validation report: excluding {len(corrupt_paths)} corrupt images.")
        else:
            print("ℹ️  No validation report found — run validate_dataset.py first for best results.")

    # --- Collect images ---
    print(f"\n📂 Scanning dataset: {dataset_dir}")
    class_images = collect_images(dataset_dir, exclude_paths=corrupt_paths)

    if not class_images:
        print("❌ No class folders with images found!")
        sys.exit(1)

    total = sum(len(imgs) for imgs in class_images.values())
    print(f"   Found {total} images across {len(class_images)} classes.\n")

    # --- Create splits ---
    print(f"✂️  Creating splits (seed={args.seed}):")
    print(f"   Train: {args.train_ratio:.0%} | Val: {args.val_ratio:.0%} | Test: {args.test_ratio:.0%}")

    splits = stratified_split(
        class_images,
        train_ratio=args.train_ratio,
        val_ratio=args.val_ratio,
        test_ratio=args.test_ratio,
        seed=args.seed,
    )

    print_split_summary(splits)

    # --- Check minimum sizes ---
    min_test_per_class = min(
        len(imgs) for imgs in splits["test"].values()
    )
    if min_test_per_class < 10:
        print(f"⚠️ Warning: Smallest test set class has only {min_test_per_class} images.")
        print("   Consider using a larger dataset or adjusting split ratios.\n")

    # --- Copy files ---
    print(f"📁 Copying images to: {output_dir}")
    manifest = copy_splits(splits, output_dir, use_symlinks=args.symlinks)

    # Add metadata to manifest
    manifest["metadata"] = {
        "source_dir": str(dataset_dir),
        "output_dir": str(output_dir),
        "train_ratio": args.train_ratio,
        "val_ratio": args.val_ratio,
        "test_ratio": args.test_ratio,
        "seed": args.seed,
        "total_images": total,
        "excluded_corrupt": len(corrupt_paths),
        "classes": sorted(class_images.keys()),
    }

    manifest_path = output_dir / "split_manifest.json"
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False, default=str)

    print(f"\n📋 Split manifest saved to: {manifest_path}")
    print(f"\n✅ Dataset split complete!")
    print(f"   Output: {output_dir}")
    print(f"   Total images: {total}")
    print(f"   Ready for model training.\n")


if __name__ == "__main__":
    main()
